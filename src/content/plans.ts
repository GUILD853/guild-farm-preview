/**
 * 滞在先1か所ぶん。
 *
 * ■ なぜ配列で持つのか
 *   いまは今市シェアハウスだけが写真と設備の情報が揃っています。
 *   三津浜の宿の情報が届いたら、同じ形で2か所目を書き足すだけで
 *   「部屋」「共用設備」「仕事環境」「周辺」「畑へのアクセス」を並べて比較できます。
 *
 * ■ 大事なルール
 *   **情報がない項目は、書かずに省いてください。**
 *   空文字や「準備中」「確認中」を入れてはいけません。
 *   表示する部品（PlansStays.tsx）は、値がない項目を丸ごと描画しません。
 */
export type Stay = {
  id: string;
  /** 滞在先の呼び名 */
  name: string;
  /** エリア（例: 松山市道後今市・道後エリア） */
  area: string;
  /** どのプランの滞在先か（例: 1ヶ月プランの滞在先） */
  usedBy: string;
  /** 滞在先の紹介。1要素＝1段落 */
  lead?: readonly string[];
  /** 全体が分かる写真（外観など） */
  photos?: readonly StayPhoto[];
  /** 個室 */
  rooms?: StayBlock;
  /** 共用部・設備 */
  facilities?: StayBlock;
  /** 仕事の環境 */
  work?: StayBlock;
  /** 周辺環境 */
  surroundings?: StayBlock;
  /** そのほかの説明ブロック（アメニティ・家のつくり など）。上から順に出ます */
  extras?: readonly StayBlock[];
  /** 所在地（公開してよい住所があるときだけ） */
  address?: string;
  /** 畑までの所要時間 */
  access?: StayAccess;
  /**
   * 確定している事実だけの短い一覧。
   * 写真や設備の情報がまだ揃っていない滞在先は、これだけを出します。
   */
  facts?: readonly string[];
  /** どんな過ごし方に向くか（根拠のある範囲でだけ書く） */
  suitedFor?: string;
};

